  function detectLocale(languages) {
    return Array.from(languages || []).some((language) => String(language).toLowerCase().startsWith("zh")) ? "zh" : "en";
  }

  function createI18n(options = {}) {
    const storage = options.storage;
    const documentRef = options.document;
    const listeners = new Set();
    let saved = null;
    try {
      saved = storage?.getItem(storageKey);
    } catch {
      // Automatic detection still works when browser storage is unavailable.
    }
    let locale = saved === "en" || saved === "zh" ? saved : detectLocale(options.languages);

    function t(key, variables = {}) {
      const template = messages[locale][key] ?? messages.en[key] ?? key;
      return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(variables, name) ? String(variables[name]) : match);
    }

    function translatePage() {
      if (!documentRef) return;
      documentRef.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
      for (const element of documentRef.querySelectorAll("[data-i18n]")) {
        element.textContent = t(element.dataset.i18n);
      }
      for (const attribute of ["aria-label", "placeholder", "title"]) {
        const dataName = `i18n${attribute.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("")}`;
        for (const element of documentRef.querySelectorAll(`[data-${attribute === "aria-label" ? "i18n-aria-label" : `i18n-${attribute}`}]`)) {
          element.setAttribute(attribute, t(element.dataset[dataName]));
        }
      }
      for (const select of documentRef.querySelectorAll("[data-language-select]")) {
        select.value = locale;
      }
    }

    function setLocale(next) {
      if (next !== "en" && next !== "zh") return;
      locale = next;
      try {
        storage?.setItem(storageKey, next);
      } catch {
        // Keep the manual choice for this page even if it cannot be persisted.
      }
      translatePage();
      for (const listener of listeners) listener(locale);
    }

    if (documentRef) {
      translatePage();
      for (const select of documentRef.querySelectorAll("[data-language-select]")) {
        select.addEventListener("change", () => setLocale(select.value));
      }
    }

    return {
      get locale() { return locale; },
      get localeTag() { return locale === "zh" ? "zh-CN" : "en-US"; },
      t,
      setLocale,
      translatePage,
      subscribe(listener) { listeners.add(listener); return () => listeners.delete(listener); },
      apiError(error) {
        if (error?.code && Object.hasOwn(messages.en, `errors.${error.code}`)) return t(`errors.${error.code}`);
        return error?.message || t("api.failed");
      },
      speakerLabel(label) {
        const match = /^说话人(\d+)$/.exec(label);
        return locale === "zh" || !match ? label : `Speaker ${match[1]}`;
      },
    };
  }

  return { createI18n, detectLocale, messages };
